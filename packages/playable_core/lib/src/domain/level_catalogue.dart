  static LevelTheme _theme({
    required BackdropStyle backdrop,
    required double craftHue,
    required double orbHue,
    required double hazardHue,
    required double skyHue,
    required double skyHueShift,
    required double skyLightness,
    required double skySaturation,
    required double gridHue,
