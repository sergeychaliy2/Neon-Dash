  }) =>
      LevelTheme(
        backdrop: backdrop,
        trim: trim,
        face: face,
        craft: ThemeColor(craftHue, 0.95, 0.55),
        orb: ThemeColor(orbHue, 0.95, 0.58),
        hazard: ThemeColor(hazardHue, 0.92, 0.52),
